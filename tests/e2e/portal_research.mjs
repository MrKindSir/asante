/** Real browser/persistence journey; deterministic workers in a disposable API. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.ASANTE_PLAYWRIGHT_MODULE || 'playwright');
const fixture = process.env.ASANTE_RESEARCH_FIXTURE_URL;
if (!fixture) throw new Error('Start the disposable research_fixture_api and set ASANTE_RESEARCH_FIXTURE_URL');
const base = process.env.ASANTE_BASE_URL || 'http://localhost';
const evidence = new URL('../../logs/tests/e2e/portal-research-activity/', import.meta.url).pathname;
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.ASANTE_BROWSER_CHANNEL || 'chrome' });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
await context.tracing.start({ screenshots: true, snapshots: true });
const page = await context.newPage();
const workerRequests = [];
let failSave = false;
await page.route('**/asante/api/**', async (route) => {
  const request = route.request();
  const path = new URL(request.url()).pathname.replace('/asante/api', '');
  if (path.endsWith('/workers') && request.method() === 'POST') workerRequests.push(request.postDataJSON());
  if (failSave && path === '/v1/workspace/projects' && request.method() === 'POST') {
    await route.fulfill({ status: 409, json: { detail: 'Deterministic browser save failure' } }); return;
  }
  const response = await route.fetch({ url: fixture + path + new URL(request.url()).search, headers: { ...request.headers(), host: new URL(base).host } });
  await route.fulfill({ response });
});
const dialog = () => page.getByRole('dialog');
const shot = (name) => page.screenshot({ path: evidence + name + '.png', fullPage: true });
const autosaved = () => dialog().locator('.form-save-status').filter({ hasText: /^Saved$/ }).waitFor();
try {
  await page.goto(base + '/asante/portal/');
  await page.getByLabel('Email', { exact: true }).fill('nomsa@asante.test');
  await page.getByLabel('Password', { exact: true }).fill('Asante-integration-nomsa-password');
  await page.getByRole('button', { name: 'Sign in →', exact: true }).click();
  await page.getByRole('button', { name: 'New story chat', exact: true }).click();
  await dialog().getByLabel('Story title').fill('Browser activity and autosave story');
  await autosaved();
  assert.equal(await dialog().count(), 1);
  await dialog().getByLabel('Claim, question, or notes').fill('When did community gatherings begin?');
  failSave = true;
  await dialog().getByRole('button', { name: 'Save and open chat', exact: true }).click();
  await dialog().getByText(/Save failed.*Deterministic browser save failure/).waitFor();
  assert.equal(await dialog().getByLabel('Story title').inputValue(), 'Browser activity and autosave story');
  failSave = false;
  await dialog().getByRole('button', { name: 'Retry autosave', exact: true }).click();
  await autosaved();
  await dialog().getByRole('button', { name: 'Save and open chat', exact: true }).click();
  await page.waitForURL(/project=/);
  assert.equal(await page.getByTestId('research-step').count(), 1);
  assert.equal(workerRequests.length, 0);
  await page.getByRole('button', { name: 'Complete research brief', exact: true }).click();
  await dialog().getByLabel('What you already know, remember, or have recorded (optional)', { exact: true }).fill('My grandmother remembers the gatherings.');
  await autosaved();
  await dialog().getByRole('button', { name: 'Close 02 / Prepare your research brief', exact: true }).click();
  await page.getByRole('button', { name: 'Complete research brief', exact: true }).click();
  assert.equal(await dialog().getByLabel('What you already know, remember, or have recorded (optional)', { exact: true }).inputValue(), 'My grandmother remembers the gatherings.');
  await dialog().getByLabel('Questions the research should answer', { exact: true }).fill('Which families attended in 1976?');
  await dialog().getByLabel('Relevant people, dates, places, and cultural context (optional)', { exact: true }).fill('Soweto families, 1976, oral history');
  await dialog().getByLabel('Research priorities (optional)', { exact: true }).fill('Preserve names');
  await dialog().getByLabel('Uncertainties to explore (optional)', { exact: true }).fill('fixture-failure');
  await autosaved();
  assert.equal(workerRequests.length, 0);
  await shot('01-autosaved-brief');
  await dialog().getByRole('button', { name: 'Close 02 / Prepare your research brief', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Edit research brief', exact: true }).click();
  assert.equal(await dialog().getByLabel('Research priorities (optional)', { exact: true }).inputValue(), 'Preserve names');
  await dialog().getByRole('button', { name: 'Save and start research', exact: true }).click();
  await page.getByRole('button', { name: 'View full research activity', exact: true }).click();
  await dialog().getByText(/Planner → Researcher/).first().waitFor();
  await dialog().getByText(/Deterministic fixture collector/).first().waitFor();
  await shot('02-live-worker-activity');
  await dialog().getByRole('button', { name: 'Close research activity', exact: true }).click();
  await page.getByText('Research failed. Your saved brief is preserved.', { exact: true }).waitFor();
  await page.getByTestId('research-step').getByRole('button', { name: 'Edit research brief', exact: true }).click();
  failSave = true;
  await dialog().getByLabel('Uncertainties to explore (optional)', { exact: true }).fill('Exact dates remain uncertain');
  await dialog().getByRole('button', { name: 'Save and start research', exact: true }).click();
  await dialog().getByText(/Save failed.*Deterministic browser save failure/).waitFor();
  assert.equal(await dialog().getByLabel('Uncertainties to explore (optional)', { exact: true }).inputValue(), 'Exact dates remain uncertain');
  assert.equal(workerRequests.length, 2);
  failSave = false;
  await dialog().getByRole('button', { name: 'Retry autosave', exact: true }).click();
  await autosaved();
  await dialog().getByRole('button', { name: 'Save and start research', exact: true }).click();
  await page.getByRole('button', { name: 'Open field report', exact: true }).waitFor();
  assert.equal(workerRequests.length, 4);
  assert.equal(workerRequests[1].expectedVersion, workerRequests[0].expectedVersion + 1);
  assert.equal(workerRequests[3].expectedVersion, workerRequests[2].expectedVersion + 1);
  await shot('03-compact-activity-results');
  await page.getByRole('button', { name: 'View full research activity', exact: true }).click();
  await dialog().getByText('Candidate sources returned (1)', { exact: true }).waitFor();
  await shot('04-full-worker-record');
  await dialog().getByRole('button', { name: 'Close research activity', exact: true }).click();
  await page.getByRole('button', { name: 'Open field report', exact: true }).click();
  await dialog().getByRole('heading', { name: 'Asante field report', exact: true }).waitFor();
  await dialog().getByRole('button', { name: 'Close Asante field report', exact: true }).click();
  await page.getByRole('button', { name: 'Open sources', exact: true }).click();
  await dialog().getByText('Deterministic candidate archive', { exact: true }).waitFor();
  await dialog().getByRole('button', { name: 'Close Candidate research sources', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: 'View full research activity', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open field report', exact: true }).waitFor();
  assert.equal(workerRequests.length, 4);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'View full research activity', exact: true }).click();
  await shot('05-mobile-worker-record');
  await dialog().getByRole('button', { name: 'Close research activity', exact: true }).click();
  await page.getByTestId('research-step').getByRole('button', { name: 'Edit research brief', exact: true }).click();
  await shot('06-mobile-autosave');
  await writeFile(evidence + 'result.json', JSON.stringify({ passed: true, base, provider: 'disposable deterministic Python workers', workerRequests, assertions: ['new project autosave stays in form', 'incomplete brief autosave', 'reopen and reload answers', 'no auto worker starts', 'save failures preserve edits', 'live delegation and collector events', 'popup detail button', 'worker failure', 'sequential saved versions', 'report/source views', 'completed reload activity persists', 'mobile activity and questionnaire'] }, null, 2));
  console.log('PASS research activity and autosave browser journey; evidence: ' + evidence);
} catch (error) {
  await shot('failure'); console.error('URL', page.url()); console.error(await page.locator('body').innerText()); throw error;
} finally {
  await context.tracing.stop({ path: evidence + 'trace.zip' }); await browser.close();
}
